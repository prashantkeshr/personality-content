"""Original exercises and programs written for Personality (MIT).

Each exercise names a `motion` from the app's built-in figure library, so no
images are needed. Text is English and Hindi; the app falls back to English.
"""


def T(en, hi):
    return {"en": en, "hi": hi}


def ex(id, category, motion, name, summary, steps_en, steps_hi, dose, safety, level="beginner"):
    return {
        "id": id,
        "category": category,
        "level": level,
        "equipment": "body weight",
        "motion": motion,
        "name": name,
        "summary": summary,
        "steps": {"en": steps_en, "hi": steps_hi},
        "dose": dose,
        "safety": safety,
        "credit": "Personality",
    }


def step(exercise, seconds=None, reps=None, rest=15, sides=False):
    s = {"exercise": exercise, "rest": rest}
    if seconds:
        s["seconds"] = seconds
    if reps:
        s["reps"] = reps
    if sides:
        s["sides"] = True
    return s


